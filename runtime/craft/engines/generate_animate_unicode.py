"""Generate Animate's character predicates from its pinned Rust standard library.

Use the same rustc as the maintained engine build. The generated module carries
Unicode properties directly, so Python's independently versioned Unicode tables
cannot silently change script class names or native trim/printable semantics.
"""
import argparse
import ast
from pathlib import Path
import subprocess
import tempfile

SOURCE = '''fn main() {
    println!("{:?}", char::UNICODE_VERSION);
    for f in [char::is_alphabetic as fn(char)->bool, char::is_numeric, char::is_whitespace] {
        let mut start=None;
        let mut ranges=Vec::new();
        for n in 0..=0x110000u32 {
            let yes=char::from_u32(n).is_some_and(f);
            if yes && start.is_none() {start=Some(n);}
            if !yes {if let Some(s)=start.take() {ranges.push((s,n-1));}}
        }
        println!("{:?}", ranges);
    }
}
'''


def generate(rustc):
    version = subprocess.check_output([rustc, '--version'], text=True).strip()
    with tempfile.TemporaryDirectory(prefix='dobe-animate-unicode-') as temp:
        source = Path(temp) / 'properties.rs'; binary = Path(temp) / 'properties'
        source.write_text(SOURCE)
        subprocess.run([rustc, str(source), '-o', str(binary)], check=True)
        lines = subprocess.check_output([str(binary)], text=True).splitlines()
    unicode, *tables = [ast.literal_eval(line) for line in lines]
    text = ('"""Generated by craft/engines/generate_animate_unicode.py; do not edit.\n\n'
            + version + '; Unicode ' + '.'.join(map(str, unicode)) + '.\n'
            'Matches native Alphabetic, Numeric and White_Space properties.\n"""\n'
            'from bisect import bisect_right\n\nUNICODE_VERSION = ' + repr(unicode) + '\n')
    for name, ranges in zip(('ALPHABETIC', 'NUMERIC', 'WHITESPACE'), tables):
        ends = [v for start, end in ranges for v in (start, end + 1)]
        text += '\n' + name + ' = (\n'
        for i in range(0, len(ends), 12):
            text += '    ' + ', '.join(map(str, ends[i:i+12])) + ',\n'
        text += ')\n'
    text += '''

def contains(table, char):
    return bisect_right(table, ord(char)) % 2 == 1


def trim(text):
    start = 0; end = len(text)
    while start < end and contains(WHITESPACE, text[start]):
        start += 1
    while end > start and contains(WHITESPACE, text[end-1]):
        end -= 1
    return text[start:end]
'''
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rustc', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.rustc))
